import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_EXECUTABLE?{executablePath:process.env.CHROMIUM_EXECUTABLE}:{})});
let checks=0;const check=(actual,expected,label)=>{assert.deepEqual(actual,expected,label);checks++;};
try{
 const page=await browser.newPage({viewport:{width:390,height:844}});
 await page.route('**/*',route=>route.abort());
 await page.setContent('<style>.hidden{display:none}</style><main></main>');
 await page.evaluate(()=>{
  window.pending=[];window.supabaseClient={rpc:()=>new Promise(resolve=>pending.push(resolve))};
 });
 await page.addScriptTag({content:fs.readFileSync('bct-handyman-operations.js','utf8')});
 check(await page.locator('#bctHandymanOpsMount').isVisible(),false,'mount starts hidden');
 await page.evaluate(()=>BCTHandymanOperations.dashboard());
 check(await page.locator('#bctHandymanOpsMount').isVisible(),true,'dashboard actually opens');
 check(await page.locator('#bctHandymanOpsMount').evaluate(el=>el.classList.contains('view')),true,'shared router includes operations');
 await page.fill('[name=code]','H-TEST');await page.fill('[name=email]','fixture@example.test');
 await page.click('#bctHLogin button');
 await page.evaluate(()=>document.dispatchEvent(new CustomEvent('bct:portal-change',{detail:{portal:'client'}})));
 check(await page.locator('#bctHandymanOpsMount').isVisible(),false,'portal change hides private operations');
 check(await page.locator('#bctHandymanOpsBody').textContent(),'','portal change clears private markup');
 await page.evaluate(()=>pending.shift()({data:[{job_number:'PRIVATE-OLD-JOB'}],error:null}));
 await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(resolve)));
 check(await page.locator('body').textContent().then(t=>t.includes('PRIVATE-OLD-JOB')),false,'late dashboard response cannot repopulate hidden content');
 await page.evaluate(()=>{window.adminTask=BCTHandymanOperations.admin()});
 check(await page.locator('#bctHandymanOpsMount').isVisible(),true,'admin operations opens');
 await page.evaluate(()=>window.dispatchEvent(new HashChangeEvent('hashchange')));
 check(await page.locator('#bctHandymanOpsMount').isVisible(),false,'hash navigation closes operations');
 await page.evaluate(async()=>{pending.splice(0).forEach(resolve=>resolve({data:[],error:null}));await adminTask});
 check(await page.locator('#bctHandymanOpsBody').textContent(),'','late admin response cannot restore old records');
 await page.evaluate(()=>BCTHandymanOperations.dashboard());
 check(await page.locator('#bctHLogin').count(),1,'dashboard reopens without duplicate form');
 await page.fill('[name=code]','H-TEST');await page.fill('[name=email]','fixture@example.test');
 await page.click('#bctHLogin button');
 check(await page.locator('#bctHLogin button').isDisabled(),true,'lookup disables duplicate submission');
 await page.evaluate(()=>document.querySelector('#bctHLogin').dispatchEvent(new Event('submit',{cancelable:true})));
 check(await page.evaluate(()=>pending.length),1,'duplicate submit never duplicates the request');
 await page.evaluate(()=>pending.shift()({data:null,error:{message:'PRIVATE SQL DETAIL'}}));
 await page.waitForFunction(()=>!document.querySelector('#bctHLogin button').disabled);
 check(await page.locator('#bctHDashRows').textContent(),'Assignments could not be loaded. Please retry.','failed lookup stays distinct from empty and sanitizes backend errors');
 await page.click('#bctHLogin button');
 await page.evaluate(()=>pending.shift()({data:[],error:null}));
 await page.waitForFunction(()=>!document.querySelector('#bctHLogin button').disabled);
 check(await page.locator('#bctHDashRows').textContent(),'No records found','successful empty retry is explicit');
 await page.evaluate(()=>BCTHandymanOperations.hide());
 check(await page.locator('#bctHandymanOpsBody').textContent(),'','explicit close clears records');
 console.log(`Handyman operations: ${checks} mocked browser assertions passed. Real Auth/RLS remains pending.`);
}finally{await browser.close();}
