import fs from 'node:fs';
import assert from 'node:assert/strict';
const root=new URL('../',import.meta.url);
const read=name=>fs.readFileSync(new URL(name,root),'utf8');
const portal=read('bct-insurance-portal.js');
const admin=read('bct-insurance-admin.js');
const loader=read('bct-admin-sections.js');
const home=read('index.html');
assert.match(portal,/if\(\$\('view-insurance'\)\)return/,'Insurance view must be created once');
assert.match(portal,/window\.bctInsurancePortalReady=true/,'Insurance portal must expose readiness only');
assert.doesNotMatch(portal,/DOMContentLoaded.*ensure/,'Insurance portal must not auto-inject on load');
assert.match(admin,/window\.bctEnsureInsuranceAdminPanel=ensure/,'Admin insurance panel must initialize on demand');
assert.match(admin,/if\(document\.getElementById\('bctInsuranceAdminPanel'\)\)return/,'Admin insurance panel must be created once');
assert.doesNotMatch(portal,/await sb\.auth\.signOut\(\)/,'Insurance authorization must not sign out existing BCT user');
assert.doesNotMatch(portal,/\.from\(['"]bct_projects['"]\)\.insert/,'No direct browser project creation');
assert.doesNotMatch(admin,/\.from\(['"]bct_projects['"]\)\.insert/,'No direct browser project creation');
assert.doesNotMatch(loader,/bct-insurance-(portal|admin)\.js/,'Keep insurance dormant until integration gates pass');
assert.doesNotMatch(home,/src=['"][^'"]*bct-insurance-(portal|admin)\.js/,'Do not inject dormant insurance into live entrypoint');
assert.match(portal,/bct_insurance_submit_claim/);
assert.match(portal,/\.from\(['"]bct_partner_claims['"]\)/,'Insurance portal must read partner claims only');
assert.match(admin,/\.from\(['"]bct_partner_claims['"]\)/,'Insurance admin must read partner claims only');
assert.doesNotMatch(portal,/\.from\(['"]bct_insurance_claims['"]\)/,'Do not read legacy insurance claims table');
assert.doesNotMatch(admin,/\.from\(['"]bct_insurance_claims['"]\)/,'Do not read legacy insurance claims table');
const preview=read('bct-insurance-preview-shell.js');
assert.match(home,/id="bctInsurancePreviewEntry"/,'Public insurance preview entry must be visible');
assert.match(home,/bct-insurance-preview-shell\\.js/,'Public insurance preview script must load');
assert.match(preview,/id='view-insurance-preview'/,'Preview has a dedicated view');
assert.match(preview,/Preview only:/,'Preview must clearly disclose it is not operational');
assert.doesNotMatch(preview,/supabaseClient|\\.rpc\\(|signInWithPassword|fetch\\(/,'Visual-only preview must not connect to insurance data');
assert.doesNotMatch(preview,/bct_insurance_claims|bct_partner_claims/,'Visual-only preview must not read claims');
assert.match(preview,/bctInsurancePreviewBack/,'Preview must have Back navigation');
assert.match(admin,/bct_admin_prepare_insurance_project_handoff/);
assert.match(portal,/A different BCT account is already signed in/,'Insurance sign-in must not replace a different active BCT account');
assert.match(portal,/if\(!user\)\{/,'Insurance sign-in should only authenticate when no account is active');
assert.match(portal,/Your insurance membership is not active/,'Claims must recheck current membership');
assert.match(portal,/Your insurance session changed/,'Claim mutation must guard against session changes');
assert.match(portal,/bctInsuranceClaimAction'\)\?\.classList\.add\('hidden'\)/,'Switching insurance tabs must close stale claim details');
console.log('TAKAI insurance static isolation and session-safety checks passed');
